import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const pluginRoot = process.cwd();
const htmlToLinkRoot = path.resolve(pluginRoot, "..", "html2url");
const sourceDir = path.join(htmlToLinkRoot, "styles", "templates");
const outputDir = path.join(pluginRoot, "src", "template-preview", "generated");
const outputFile = path.join(outputDir, "template-styles.ts");

const templateCssFiles = {
	memo: "memo.css",
	popart: "popart.css",
	traditionalchinese: "traditionalchinese.css",
	coilnotebook: "coilnotebook.css",
	purpleticket: "purpleticket.css",
	bytedance: "byteDance.css",
	warm: "warm.css",
	alibaba: "alibaba.css",
	notebook: "notebook.css",
	darktech: "darktech.css",
	fairytale: "fairytale.css",
	boardgamestyle: "boardgamestyle.css",
	cyberpunk: "cyberpunk.css",
	glassmorphism: "glassmorphism.css",
	neonglow: "neonGlow.css",
	vintagenewspaper: "vintagenewspaper.css",
	handwrittennote: "handwrittennote.css",
	vintagemap: "vintagemap.css",
	blueprint: "blueprint.css",
	botanical: "botanical.css",
	sketch: "sketch.css",
	terminal: "terminal.css",
	retro: "retro.css",
	ayulight: "ayulight.css",
	bauhaus: "bauhaus.css",
	greensimple: "greensimple.css",
	maximalism: "maximalism.css",
	neobrutalism: "neobrutalism.css",
	newsprint: "newsprint.css",
	organic: "organic.css",
	playfulgeometric: "playfulgeometric.css",
	professional: "professional.css",
	plain: "plain.css",
};

async function readCss(fileName) {
	return readFile(path.join(sourceDir, fileName), "utf8");
}

const commonCss = await readCss("common.css");
const styles = {};
for (const [templateId, fileName] of Object.entries(templateCssFiles)) {
	styles[templateId] = await readCss(fileName);
}

await mkdir(outputDir, { recursive: true });
const generated = `/**\n * Generated by scripts/sync-template-assets.mjs.\n * Source: ../html2url/styles/templates\n * Do not edit manually.\n */\nexport const COMMON_TEMPLATE_STYLES = ${JSON.stringify(commonCss)};\nexport const TEMPLATE_STYLES: Record<string, string> = ${JSON.stringify(styles, null, 2)};\n`;
await writeFile(outputFile, generated, "utf8");
console.log(`Synced ${Object.keys(styles).length} templates to ${path.relative(pluginRoot, outputFile)}`);
